// Writes docs/contrast-report.md: the pairs F5 might check, for every palette and mode.
import { readFileSync, writeFileSync } from 'node:fs';
import { createState, resolve } from '../src/palette';
import { colorDistance, contrastRatio } from '../src/tokens/color';
import type { Mode, ResolvedTokens, TokenName } from '../src/tokens/types';

interface Palette { name: string; tests: string; colors: string[]; primary: number }
const palettes = JSON.parse(readFileSync('fixtures/palettes.json', 'utf8')) as Palette[];

const COLUMNS: { label: string; mode: Mode; recede: number }[] = [
  { label: 'light', mode: 'light', recede: 0 },
  { label: 'dark', mode: 'dark', recede: 0 },
  { label: 'data 60', mode: 'data', recede: 60 },
  { label: 'data 100', mode: 'data', recede: 100 },
];

// Targets: labels 7:1 (primary) and 4.5:1 (secondary); map features against land 3:1.
const PAIRS: { a: TokenName; b: TokenName; target: number; group: string }[] = [
  ...(['land', 'water', 'park', 'building', 'roadMajor', 'roadMinor'] as TokenName[]).map((b) => ({ a: 'labelPrimary' as TokenName, b, target: 7, group: 'Label on surface' })),
  ...(['land', 'water', 'park', 'building', 'roadMajor', 'roadMinor'] as TokenName[]).map((b) => ({ a: 'labelSecondary' as TokenName, b, target: 4.5, group: 'Label on surface' })),
  { a: 'accent', b: 'land', target: 4.5, group: 'Text colour' },
  ...(['roadMajor', 'boundary'] as TokenName[]).map((a) => ({ a, b: 'land' as TokenName, target: 3, group: 'Feature against land' })),
  { a: 'roadMinor', b: 'land', target: 1.5, group: 'Feature against land' },
  { a: 'roadMajor', b: 'roadMinor', target: 1.5, group: 'Hierarchy' },
];

// F5 decision (Checkpoint A2): roadMajor against land needs 3 in light and dark, and in data mode the
// threshold slides linearly from 3 at recede 0 to 1.5 at recede 100.
const targetFor = (a: TokenName, b: TokenName, target: number, column: (typeof COLUMNS)[number]) =>
  column.mode !== 'data' ? target
    : a === 'roadMajor' && b === 'land' ? 3 - 1.5 * (column.recede / 100)
    : a === 'roadMinor' && b === 'land' ? 0 // quiet by design in data mode: reported, not checked
    : target;

const compute = (palette: Palette, column: (typeof COLUMNS)[number]): ResolvedTokens =>
  resolve({ ...createState({ colors: palette.colors, primary: palette.primary }), mode: column.mode, recede: column.recede }).tokens;

const fail = Object.fromEntries(COLUMNS.map((column) => [column.label, 0]));
// Pair -> column -> palettes below target.
const failing: Record<string, Record<string, string[]>> = {};
const sections = palettes.map((palette, index) => {
  const sets = COLUMNS.map((column) => compute(palette, column));
  const dist = (token: TokenName) => sets.map((tokens) => colorDistance(tokens[token], tokens.land).toFixed(3));
  const distRows = (['water', 'park'] as TokenName[]).map((token) => `| ${token} / land | ${dist(token).join(' | ')} |`);
  const rows = PAIRS.map(({ a, b, target }) => {
    const cells = sets.map((tokens, c) => {
      const ratio = contrastRatio(tokens[a], tokens[b]);
      const ok = ratio >= targetFor(a, b, target, COLUMNS[c]);
      if (!ok) {
        fail[COLUMNS[c].label]++;
        ((failing[`${a} / ${b}`] ??= {})[COLUMNS[c].label] ??= []).push(palette.name);
      }
      return `${ratio.toFixed(2)}${ok ? '' : ' ✗'}`;
    });
    const shown = a === 'roadMajor' && b === 'land' ? '3, data 3→1.5' : `${target}`;
    return `| ${a} / ${b} | ${shown} | ${cells.join(' | ')} |`;
  });
  return [
    `### ${index + 1}. ${palette.name}`,
    '',
    `${palette.colors.join(' ')}. ${palette.tests}.`,
    '',
    `| Pair (foreground / background) | Target | ${COLUMNS.map((c) => c.label).join(' | ')} |`,
    `| --- | --- | ${COLUMNS.map(() => '---').join(' | ')} |`,
    ...rows,
    '',
    `| OKLab distance from land | ${COLUMNS.map((c) => c.label).join(' | ')} |`,
    `| --- | ${COLUMNS.map(() => '---').join(' | ')} |`,
    ...distRows,
    '',
  ].join('\n');
});

const distTable = (token: TokenName) => {
  const ordered = [...palettes].sort((x, y) => (x.name === 'Fjord Bank' ? -1 : y.name === 'Fjord Bank' ? 1 : 0));
  return ordered.map((palette) => {
    const cells = COLUMNS.map((column) => colorDistance(compute(palette, column)[token], compute(palette, column).land).toFixed(3));
    return `| ${palette.name} | ${cells.join(' | ')} |`;
  }).join('\n');
};

const pairSummary = PAIRS.map(({ a, b, target }) => {
  const byColumn = failing[`${a} / ${b}`] ?? {};
  const counts = COLUMNS.map((column) => `${byColumn[column.label]?.length ?? 0}`);
  const shown = a === 'roadMajor' && b === 'land' ? '3, data 3→1.5' : `${target}`;
  return `| ${a} / ${b} | ${shown} | ${counts.join(' | ')} |`;
}).join('\n');

writeFileSync('docs/contrast-report.md', `# Contrast report

Generated by \`npm run contrast-report\`. Do not edit.

WCAG contrast ratios between the pairs F5 might check, for each of the ten palettes in light, dark and data mode at recede 60 and 100. A ✗ marks a pair below its target. Targets (F5 decisions from Checkpoint A2): label primary 7, label secondary 4.5, accent text 4.5, roadMajor and boundary against land 3, roadMinor against land 1.5, and a 1.5 floor on roadMajor against roadMinor as a hierarchy cue. In data mode roadMinor / land is reported but not checked, and the roadMajor / land target slides linearly from 3 at recede 0 to 1.5 at recede 100 (2.1 at 60). Water and park are not checked by ratio: they use an OKLab distance from land, tabulated below so the threshold can be set.

## Water and park: OKLab distance from land

About 0.02 is a just-noticeable difference. Fjord Bank first, since it is the case where the brand blue collides with water. Columns are light, dark, data 60, data 100.

### water / land

| Palette | ${COLUMNS.map((c) => c.label).join(' | ')} |
| --- | ${COLUMNS.map(() => '---').join(' | ')} |
${distTable('water')}

### park / land

| Palette | ${COLUMNS.map((c) => c.label).join(' | ')} |
| --- | ${COLUMNS.map(() => '---').join(' | ')} |
${distTable('park')}

## Failing pairs by count

Palettes below target, out of ${palettes.length}, for each pair and column.

| Pair | Target | ${COLUMNS.map((c) => c.label).join(' | ')} |
| --- | --- | ${COLUMNS.map(() => '---').join(' | ')} |
${pairSummary}

## Failures per column

${COLUMNS.map((column) => `- ${column.label}: ${fail[column.label]} of ${palettes.length * PAIRS.length} pair checks`).join('\n')}

## Tables

${sections.join('\n')}`);
console.log('failures per column:', JSON.stringify(fail));
