// Writes docs/contrast-report.md: the pairs F5 might check, for every palette and mode.
import { readFileSync, writeFileSync } from 'node:fs';
import { createState, resolve } from '../src/palette';
import { contrastRatio } from '../src/tokens/color';
import type { Mode, ResolvedTokens, TokenName } from '../src/tokens/types';

interface Palette { name: string; tests: string; colors: string[]; primary: number }
const palettes = JSON.parse(readFileSync('fixtures/palettes.json', 'utf8')) as Palette[];

const COLUMNS: { label: string; mode: Mode; recede: number }[] = [
  { label: 'light', mode: 'light', recede: 0 },
  { label: 'dark', mode: 'dark', recede: 0 },
  { label: 'data 60', mode: 'data', recede: 60 },
  { label: 'data 100', mode: 'data', recede: 100 },
];

// Targets: labels 7:1 (primary) and 4.5:1 (secondary); map features against land 3:1.
const PAIRS: { a: TokenName; b: TokenName; target: number; group: string }[] = [
  ...(['land', 'water', 'park', 'building', 'roadMajor', 'roadMinor'] as TokenName[]).map((b) => ({ a: 'labelPrimary' as TokenName, b, target: 7, group: 'Label on surface' })),
  ...(['land', 'water', 'park', 'building', 'roadMajor', 'roadMinor'] as TokenName[]).map((b) => ({ a: 'labelSecondary' as TokenName, b, target: 4.5, group: 'Label on surface' })),
  { a: 'accent', b: 'land', target: 4.5, group: 'Text colour' },
  ...(['roadMajor', 'roadMinor', 'water', 'boundary'] as TokenName[]).map((a) => ({ a, b: 'land' as TokenName, target: 3, group: 'Feature against land' })),
  { a: 'roadMajor', b: 'roadMinor', target: 1.5, group: 'Hierarchy' },
];

const compute = (palette: Palette, column: (typeof COLUMNS)[number]): ResolvedTokens =>
  resolve({ ...createState({ colors: palette.colors, primary: palette.primary }), mode: column.mode, recede: column.recede }).tokens;

const fail = Object.fromEntries(COLUMNS.map((column) => [column.label, 0]));
// Pair -> column -> palettes below target.
const failing: Record<string, Record<string, string[]>> = {};
const sections = palettes.map((palette, index) => {
  const sets = COLUMNS.map((column) => compute(palette, column));
  const rows = PAIRS.map(({ a, b, target }) => {
    const cells = sets.map((tokens, c) => {
      const ratio = contrastRatio(tokens[a], tokens[b]);
      const ok = ratio >= target;
      if (!ok) {
        fail[COLUMNS[c].label]++;
        ((failing[`${a} / ${b}`] ??= {})[COLUMNS[c].label] ??= []).push(palette.name);
      }
      return `${ratio.toFixed(2)}${ok ? '' : ' ✗'}`;
    });
    return `| ${a} / ${b} | ${target} | ${cells.join(' | ')} |`;
  });
  return [
    `### ${index + 1}. ${palette.name}`,
    '',
    `${palette.colors.join(' ')}. ${palette.tests}.`,
    '',
    `| Pair (foreground / background) | Target | ${COLUMNS.map((c) => c.label).join(' | ')} |`,
    `| --- | --- | ${COLUMNS.map(() => '---').join(' | ')} |`,
    ...rows,
    '',
  ].join('\n');
});

const pairSummary = PAIRS.map(({ a, b, target }) => {
  const byColumn = failing[`${a} / ${b}`] ?? {};
  const counts = COLUMNS.map((column) => `${byColumn[column.label]?.length ?? 0}`);
  return `| ${a} / ${b} | ${target} | ${counts.join(' | ')} |`;
}).join('\n');

writeFileSync('docs/contrast-report.md', `# Contrast report

Generated by \`npm run contrast-report\`. Do not edit.

WCAG contrast ratios between the pairs F5 might check, for each of the ten palettes in light, dark and data mode at recede 60 and 100. A ✗ marks a pair below its target. Targets: label primary 7, label secondary 4.5, accent text 4.5, map features against land 3, and a 1.5 floor on roadMajor against roadMinor as a hierarchy cue.

Data mode lowers feature contrast on purpose, so its feature failures are expected. The threshold for data mode is an open decision, and the data 100 column is the evidence for it.

## Failing pairs by count

Palettes below target, out of ${palettes.length}, for each pair and column.

| Pair | Target | ${COLUMNS.map((c) => c.label).join(' | ')} |
| --- | --- | ${COLUMNS.map(() => '---').join(' | ')} |
${pairSummary}

## Failures per column

${COLUMNS.map((column) => `- ${column.label}: ${fail[column.label]} of ${palettes.length * PAIRS.length} pair checks`).join('\n')}

## Tables

${sections.join('\n')}`);
console.log('failures per column:', JSON.stringify(fail));
